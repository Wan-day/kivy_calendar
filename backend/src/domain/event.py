"""The calendar event domain model.

Times are kept together with an explicit IANA time zone name.  The zone name is
stored separately from the instant so it survives serialisation to Google
Calendar and to the local SQLite cache.
"""

from __future__ import annotations

from datetime import datetime
from typing import Self
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator


class Event(BaseModel):
    """A calendar event.

    The ``id`` is generated by the client so retrying a create cannot produce a
    duplicate event.  ``start`` and ``end`` must be timezone-aware and are
    normalised to the declared IANA zones.
    """

    model_config = ConfigDict(extra="forbid")

    id: str = Field(min_length=1, max_length=1024)
    calendar_id: str = Field(default="", max_length=1024)
    start: datetime
    end: datetime
    start_timezone: str
    end_timezone: str
    summary: str = ""
    description: str | None = None
    recurrence: list[str] | None = None
    extended_properties: dict[str, str] = Field(default_factory=dict)

    @field_validator("id")
    @classmethod
    def _id_must_not_be_blank(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("event id must not be blank")
        return value

    @field_validator("start", "end")
    @classmethod
    def _datetime_must_have_timezone(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("datetimes must include time zone information")
        return value

    @field_validator("start_timezone", "end_timezone")
    @classmethod
    def _timezone_must_be_iana(cls, value: str) -> str:
        if not value.strip():
            raise ValueError("time zone name must not be blank")
        try:
            ZoneInfo(value)
        except (ValueError, ZoneInfoNotFoundError) as exc:
            raise ValueError(f"unknown IANA time zone: {value!r}") from exc
        return value

    @field_validator("recurrence")
    @classmethod
    def _recurrence_rules_must_not_be_blank(
        cls, value: list[str] | None
    ) -> list[str] | None:
        if value is not None and any(not rule.strip() for rule in value):
            raise ValueError("recurrence rules must not be blank")
        return value

    @field_validator("extended_properties")
    @classmethod
    def _extended_property_keys_must_not_be_blank(
        cls, value: dict[str, str]
    ) -> dict[str, str]:
        if any(not key.strip() for key in value):
            raise ValueError("extended property keys must not be blank")
        return value

    @model_validator(mode="after")
    def _normalise_times_to_declared_zones(self) -> Self:
        self.start = self.start.astimezone(ZoneInfo(self.start_timezone))
        self.end = self.end.astimezone(ZoneInfo(self.end_timezone))
        if self.end <= self.start:
            raise ValueError("event end must be after start")
        return self
