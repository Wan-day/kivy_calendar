"""The calendar provider contract.

Google Calendar is the source of truth.  The sync service talks to it only
through this interface, so every event the app accepts is written to the
calendar before it is shown as saved or cached locally.  Implementations return
expected failures (offline, rate limits, upstream errors) as ``Result`` values;
they never let those failures escape as exceptions across a module boundary.
"""

from __future__ import annotations

from enum import StrEnum
from typing import Protocol, runtime_checkable

from core.errors import Result
from domain.event import Event


class ProviderOperation(StrEnum):
    """Operations a provider can perform, used for failure injection."""

    CREATE = "create_event"
    UPDATE = "update_event"
    DELETE = "delete_event"
    GET = "get_event"
    LIST = "list_events"


@runtime_checkable
class CalendarProvider(Protocol):
    """Calendar operations required by the sync service.

    An event's ``id`` is generated by the client before it reaches the provider,
    so retrying a create can never produce a duplicate event.  Implementations
    use that id as the upstream event key and report an ``ALREADY_EXISTS`` error
    when a create targets an id the calendar already holds.
    """

    def create_event(self, event: Event) -> Result[Event]:
        """Write ``event`` to the upstream calendar and return the saved copy.

        The event is not saved until this call succeeds; callers must not cache
        or display it before the provider confirms it.
        """
        ...

    def update_event(self, event: Event) -> Result[Event]:
        """Replace the upstream event with the same id and return the saved copy."""
        ...

    def delete_event(self, event_id: str) -> Result[None]:
        """Delete the upstream event with ``event_id``.

        Returns ``NOT_FOUND`` when the calendar does not hold the event.
        """
        ...

    def get_event(self, event_id: str) -> Result[Event | None]:
        """Return the upstream event, or ``None`` when it does not exist."""
        ...

    def list_events(self) -> Result[list[Event]]:
        """Return every event in the upstream calendar."""
        ...
