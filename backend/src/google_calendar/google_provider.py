"""The real Google Calendar provider.

This adapter implements the :class:`~google_calendar.provider.CalendarProvider`
contract on top of the Google Calendar v3 API.  It is deliberately the only
module that knows Google's payload shape: the domain :class:`~domain.event.Event`
is mapped to ``summary``, ``description``, ``start``/``end``, ``recurrence``,
the client-generated id, and ``extendedProperties.private``.

Only private extended properties are round-tripped.  Google also exposes shared
and private properties to different audiences; the backend treats its own
metadata as private so other apps cannot overwrite it.  Google limits private
properties to roughly 300 entries, with keys up to 44 characters and values up
to 1024 characters; callers should keep metadata small.

Event ids are generated by the caller, but Google only accepts 5-1024
characters from the base32hex alphabet ``[0-9a-v]``.  Create and update reject
anything else with ``INVALID_ARGUMENT`` before calling Google;
:func:`generate_event_id` returns a UUID hex string that is always valid.

All-day events use Google's ``date`` fields instead of ``dateTime``.  The
domain model keeps them as midnight-to-midnight timed values flagged with
``all_day``, so the rest of the app can treat them like any other event while
the provider translates between the two shapes.

Timed events normally repeat their IANA zone in Google's ``timeZone`` field.
Some events created by other clients instead carry only an offset inside the
ISO ``dateTime`` string.  A zero offset is mapped to ``UTC``; an event with a
non-zero offset and no ``timeZone`` cannot be mapped to an IANA zone, so
:meth:`GoogleCalendarProvider.list_events` skips it and
:meth:`GoogleCalendarProvider.get_event` returns ``INVALID_EVENT``.

Recurring events are expanded into one concrete event per occurrence by
:func:`~google_calendar.recurrence.expand_event`, so repeats show up as
separate events in the sync cache and in free-slot searches.

Expected failures are mapped to :class:`~core.errors.Result` values:

===========  =========================================
HTTP status  Error code
===========  =========================================
400          ``INVALID_ARGUMENT``
401          ``AUTH_ERROR``
404 / 410    ``NOT_FOUND``
409          ``ALREADY_EXISTS``
429 / 5xx    ``UPSTREAM_ERROR``
other        ``UPSTREAM_ERROR``
===========  =========================================

401 responses and OAuth refresh failures (:class:`google.auth.exceptions.RefreshError`)
are permanent ``AUTH_ERROR`` failures.  403 is treated as a retryable
``UPSTREAM_ERROR`` because reliably distinguishing quota/rate-limit reasons
from a revoked grant requires parsing Google's error payload; the job will
eventually exhaust its retries instead.

Network timeouts and connection failures also become ``UPSTREAM_ERROR``.
Operational exceptions never escape the provider.
"""

from __future__ import annotations

import re
import uuid
from collections.abc import Callable
from datetime import date, datetime, timedelta
from typing import Any
from zoneinfo import ZoneInfo

from google.auth.exceptions import RefreshError
from google.oauth2.credentials import Credentials
from googleapiclient.discovery import build  # type: ignore[import-untyped]
from googleapiclient.errors import HttpError  # type: ignore[import-untyped]

from core.errors import Error, ErrorCode, Result
from domain.event import Event
from google_calendar.recurrence import expand_event

DEFAULT_CALENDAR_ID = "primary"
MAX_RESULTS = 2500

_READABLE_ACCESS_ROLES = frozenset({"owner", "writer", "reader"})
_CALENDAR_LIST_AUTH_MESSAGE = (
    "Google Calendar calendar list access failed: the OAuth refresh token "
    "does not grant the calendar.calendarlist.readonly scope. Re-run "
    "`PYTHONPATH=backend/src python -m google_calendar.auth` to grant it, then "
    "update GOOGLE_REFRESH_TOKEN."
)

MIN_EVENT_ID_LENGTH = 5
MAX_EVENT_ID_LENGTH = 1024
_EVENT_ID_PATTERN = re.compile(
    rf"^[0-9a-v]{{{MIN_EVENT_ID_LENGTH},{MAX_EVENT_ID_LENGTH}}}$"
)


def generate_event_id() -> str:
    """Return a random event id that satisfies Google's constraints.

    Google requires 5-1024 characters from the base32hex alphabet
    ``[0-9a-v]``.  ``uuid.uuid4().hex`` is 32 lowercase hexadecimal digits, so
    it is always a valid Google event id.
    """
    return uuid.uuid4().hex


class GoogleCalendarProvider:
    """A :class:`~google_calendar.provider.CalendarProvider` backed by Google."""

    def __init__(
        self,
        service: Any,
        calendar_id: str = DEFAULT_CALENDAR_ID,
        time_zone: str = "UTC",
    ) -> None:
        if not calendar_id.strip():
            raise ValueError("calendar_id must not be blank")
        self._service = service
        self._calendar_id = calendar_id
        self._time_zone = time_zone

    @classmethod
    def from_credentials(
        cls,
        credentials: Credentials,
        calendar_id: str = DEFAULT_CALENDAR_ID,
        time_zone: str = "UTC",
    ) -> Result[GoogleCalendarProvider]:
        """Build a provider from OAuth credentials.

        The discovery client is created once and reused for every request.
        Service-construction failures are returned as ``UPSTREAM_ERROR``.
        """
        if not calendar_id.strip():
            return Result.fail(
                ErrorCode.INVALID_ARGUMENT,
                "calendar_id must not be blank",
            )
        try:
            service = build(
                "calendar",
                "v3",
                credentials=credentials,
                cache_discovery=False,
            )
        except Exception as exc:
            return Result.fail(
                ErrorCode.UPSTREAM_ERROR,
                f"could not build the Google Calendar service: {exc}",
            )
        return Result.ok(cls(service, calendar_id, time_zone=time_zone))

    def create_event(self, event: Event) -> Result[Event]:
        """Insert ``event`` with its client-generated id, or as a series override.

        An event that carries a ``recurring_event_id`` targets one occurrence
        slot of a recurring series, so the Google insert creates or replaces that
        override instead of creating a standalone event.
        """
        calendar_id = event.calendar_id or self._calendar_id
        if event.recurring_event_id:
            return self._event_request(
                lambda: self._service.events().insert(
                    calendarId=calendar_id,
                    body=_event_to_payload(event),
                ),
                calendar_id,
            )
        invalid = _event_id_error(event.id)
        if invalid is not None:
            return Result.fail(invalid.code, invalid.message)
        return self._event_request(
            lambda: self._service.events().insert(
                calendarId=calendar_id,
                body=_event_to_payload(event),
            ),
            calendar_id,
        )

    def update_event(self, event: Event) -> Result[Event]:
        """Patch the upstream event that has the same id, or an occurrence slot.

        ``patch`` only changes the fields the backend sends, so data this
        adapter does not model (location, attendees, reminders, ...) survives.

        An event that carries a ``recurring_event_id`` edits one occurrence slot
        of a recurring series through an override instead of patching the series.
        """
        calendar_id = event.calendar_id or self._calendar_id
        if event.recurring_event_id:
            return self._event_request(
                lambda: self._service.events().insert(
                    calendarId=calendar_id,
                    body=_event_to_payload(event),
                ),
                calendar_id,
            )
        invalid = _event_id_error(event.id)
        if invalid is not None:
            return Result.fail(invalid.code, invalid.message)
        return self._event_request(
            lambda: self._service.events().patch(
                calendarId=calendar_id,
                eventId=event.id,
                body=_event_to_payload(event),
            ),
            calendar_id,
        )

    def delete_event(self, calendar_id: str, event_id: str) -> Result[None]:
        """Delete the upstream event, reporting a missing event as an error."""
        target = calendar_id or self._calendar_id
        response = self._execute(
            lambda: self._service.events().delete(
                calendarId=target,
                eventId=event_id,
            )
        )
        if response.error is not None:
            return Result.fail(response.error.code, response.error.message)
        return Result.ok(None)

    def get_event(
        self,
        calendar_id: str,
        event_id: str,
    ) -> Result[Event | None]:
        """Return the upstream event, or ``None`` when Google does not have it."""
        target = calendar_id or self._calendar_id
        response = self._execute(
            lambda: self._service.events().get(
                calendarId=target,
                eventId=event_id,
            )
        )
        if response.error is not None:
            if response.error.code is ErrorCode.NOT_FOUND:
                return Result.ok(None)
            return Result.fail(response.error.code, response.error.message)

        mapped = _event_from_resource(response.value, target, self._time_zone)
        if mapped.error is not None:
            return Result.fail(mapped.error.code, mapped.error.message)
        return Result.ok(mapped.value)

    def list_events(self) -> Result[list[Event]]:
        """Return every event from every readable calendar.

        Google can expose the same event through more than one calendar, so
        duplicate ids are collapsed to the first calendar that lists them.
        """
        calendars = self._calendar_ids()
        if calendars.error is not None:
            return Result.fail(calendars.error.code, calendars.error.message)

        events: list[Event] = []
        seen: set[str] = set()
        for calendar_id in calendars.value or []:
            listed = self._list_calendar_events(calendar_id)
            if listed.error is not None:
                return Result.fail(listed.error.code, listed.error.message)
            for event in listed.value or []:
                for candidate in expand_event(event):
                    if candidate.id in seen:
                        continue
                    seen.add(candidate.id)
                    events.append(candidate)
        return Result.ok(events)

    def _calendar_ids(self) -> Result[list[str]]:
        """Return the configured default calendar and every readable calendar."""
        calendar_ids = [self._calendar_id]
        page_token: str | None = None
        while True:
            query: dict[str, Any] = {"maxResults": MAX_RESULTS}
            if page_token is not None:
                query["pageToken"] = page_token
            response = self._calendar_list_request(
                lambda: self._service.calendarList().list(**query)
            )
            if response.error is not None:
                return Result.fail(response.error.code, response.error.message)

            items = _items_from_response(response.value, description="calendar")
            if items.error is not None:
                return Result.fail(items.error.code, items.error.message)
            for item in items.value or []:
                calendar_id = _readable_calendar_id(item)
                if calendar_id is not None and calendar_id not in calendar_ids:
                    calendar_ids.append(calendar_id)

            page_token = _next_page_token(response.value)
            if page_token is None:
                break
        return Result.ok(calendar_ids)

    def _list_calendar_events(self, calendar_id: str) -> Result[list[Event]]:
        """Return every timed event in one calendar, following pagination."""
        events: list[Event] = []
        page_token: str | None = None
        while True:
            query: dict[str, Any] = {
                "calendarId": calendar_id,
                "maxResults": MAX_RESULTS,
                "singleEvents": False,
                "showDeleted": False,
            }
            if page_token is not None:
                query["pageToken"] = page_token
            response = self._execute(
                lambda: self._service.events().list(**query)
            )
            if response.error is not None:
                return Result.fail(response.error.code, response.error.message)

            items = _items_from_response(response.value)
            if items.error is not None:
                return Result.fail(items.error.code, items.error.message)
            for item in items.value or []:
                mapped = _event_from_resource(item, calendar_id, self._time_zone)
                if mapped.error is not None:
                    # One unmappable entry (an all-day event or an offset-only
                    # event without an IANA zone) must not abort the whole sync.
                    continue
                if mapped.value is not None:
                    events.append(mapped.value)

            page_token = _next_page_token(response.value)
            if page_token is None:
                break
        return Result.ok(events)

    def _calendar_list_request(self, request: Callable[[], Any]) -> Result[Any]:
        """Execute a calendar-list request with scope-specific auth errors."""
        try:
            response: Any = request().execute()
        except Exception as exc:
            if isinstance(exc, RefreshError) or (
                isinstance(exc, HttpError) and _http_status(exc) in (401, 403)
            ):
                return Result.fail(ErrorCode.AUTH_ERROR, _CALENDAR_LIST_AUTH_MESSAGE)
            failure = _error_from_exception(exc)
            return Result.fail(failure.code, failure.message)
        return Result.ok(response)

    def _event_request(
        self,
        request: Callable[[], Any],
        calendar_id: str,
    ) -> Result[Event]:
        """Execute a request whose response is a Google event resource."""
        response = self._execute(request)
        if response.error is not None:
            return Result.fail(response.error.code, response.error.message)
        return _event_from_resource(response.value, calendar_id, self._time_zone)

    def _execute(self, request: Callable[[], Any]) -> Result[Any]:
        """Build and execute one Google request, mapping every failure."""
        try:
            response: Any = request().execute()
        except Exception as exc:
            failure = _error_from_exception(exc)
            return Result.fail(failure.code, failure.message)
        return Result.ok(response)


def _event_id_error(event_id: str) -> Error | None:
    """Return an error when ``event_id`` violates Google's id constraints."""
    if _EVENT_ID_PATTERN.fullmatch(event_id) is not None:
        return None
    return Error(
        ErrorCode.INVALID_ARGUMENT,
        "Google Calendar event ids must be 5-1024 characters from the "
        f"base32hex alphabet [0-9a-v]; got {event_id!r}",
    )


def _event_to_payload(event: Event) -> dict[str, Any]:
    """Map the domain event onto a Google Calendar ``events`` payload."""
    payload: dict[str, Any] = {
        "summary": event.summary,
        "extendedProperties": {"private": dict(event.extended_properties)},
    }
    if event.all_day:
        # All-day events use date-only values; the end date is exclusive.
        payload["start"] = {"date": _event_date(event.start)}
        payload["end"] = {"date": _event_date(event.end)}
    else:
        payload["start"] = {
            "dateTime": event.start.isoformat(),
            "timeZone": event.start_timezone,
        }
        payload["end"] = {
            "dateTime": event.end.isoformat(),
            "timeZone": event.end_timezone,
        }
    if event.recurring_event_id:
        # An occurrence edit targets one slot of a recurring series.
        payload["recurringEventId"] = event.recurring_event_id
    else:
        payload["id"] = event.id
        if event.recurrence is not None:
            payload["recurrence"] = list(event.recurrence)
    if event.description is not None:
        payload["description"] = event.description
    return payload


def _event_date(moment: datetime) -> str:
    """Return the local calendar date for an all-day bound."""
    return moment.date().isoformat()


def _all_day_event(
    raw: dict[str, Any],
    calendar_id: str,
    time_zone: str,
) -> Result[Event]:
    """Map a Google all-day resource onto the domain model.

    All-day events cover whole calendar days, so the domain keeps them as
    midnight-to-midnight datetimes in the calendar's time zone and flags them
    with ``all_day``.  The Google end date is exclusive, which becomes the
    event duration; a missing or degenerate end falls back to a single day.
    """
    event_id = raw.get("id")
    start_value = raw.get("start")
    end_value = raw.get("end")
    start_text = start_value.get("date") if isinstance(start_value, dict) else None
    end_text = end_value.get("date") if isinstance(end_value, dict) else None
    if (
        not isinstance(event_id, str)
        or not event_id.strip()
        or not isinstance(start_text, str)
        or not start_text.strip()
        or not isinstance(end_text, str)
        or not end_text.strip()
    ):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            "Google Calendar returned an event with invalid all-day bounds",
        )
    try:
        start_date = date.fromisoformat(start_text.strip())
        end_date = date.fromisoformat(end_text.strip())
    except ValueError:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar returned an event {event_id!r} with an "
            "invalid all-day date",
        )
    duration = end_date - start_date
    if duration <= timedelta(0):
        duration = timedelta(days=1)
    try:
        zone = ZoneInfo(time_zone)
    except Exception:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar event {event_id!r} has an unknown time zone: "
            f"{time_zone!r}",
        )
    start = datetime(start_date.year, start_date.month, start_date.day, tzinfo=zone)
    end = start + duration
    recurring_event_id = raw.get("recurringEventId")
    if recurring_event_id is not None and not isinstance(recurring_event_id, str):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} has an invalid recurring event id",
        )
    extended_properties: dict[str, str] = {}
    extended = raw.get("extendedProperties")
    if isinstance(extended, dict):
        private = extended.get("private", {})
        if isinstance(private, dict):
            extended_properties = {
                str(key): str(value) for key, value in private.items()
            }
    try:
        return Result.ok(
            Event(
                id=event_id,
                calendar_id=calendar_id,
                recurring_event_id=recurring_event_id,
                all_day=True,
                summary=str(raw.get("summary") or ""),
                description=(
                    str(raw["description"])
                    if isinstance(raw.get("description"), str)
                    else None
                ),
                start=start,
                end=end,
                start_timezone=time_zone,
                end_timezone=time_zone,
                recurrence=(
                    list(raw["recurrence"])
                    if isinstance(raw.get("recurrence"), list)
                    else None
                ),
                extended_properties=extended_properties,
            )
        )
    except ValueError as exc:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar returned an invalid event {event_id!r}: {exc}",
        )


def _event_from_resource(
    raw: object,
    calendar_id: str,
    time_zone: str = "UTC",
) -> Result[Event]:
    """Map a Google event resource back onto the domain model."""
    if not isinstance(raw, dict):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            "Google Calendar returned an event that is not an object",
        )
    if _is_all_day_resource(raw):
        return _all_day_event(raw, calendar_id, time_zone)

    event_id = raw.get("id")
    if not isinstance(event_id, str) or not event_id.strip():
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            "Google Calendar returned an event without an id",
        )

    summary = raw.get("summary", "")
    if summary is None:
        summary = ""
    if not isinstance(summary, str):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} has an invalid summary",
        )

    description = raw.get("description")
    if description is not None and not isinstance(description, str):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} has an invalid description",
        )

    recurrence = raw.get("recurrence")
    if recurrence is not None and (
        not isinstance(recurrence, list)
        or any(not isinstance(rule, str) for rule in recurrence)
    ):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} has invalid recurrence rules",
        )

    extended_properties = raw.get("extendedProperties")
    private_properties: dict[str, str] = {}
    if extended_properties is not None:
        if not isinstance(extended_properties, dict):
            return Result.fail(
                ErrorCode.INVALID_EVENT,
                f"event {event_id!r} has invalid extended properties",
            )
        private = extended_properties.get("private", {})
        if not isinstance(private, dict) or any(
            not isinstance(key, str) or not isinstance(value, str)
            for key, value in private.items()
        ):
            return Result.fail(
                ErrorCode.INVALID_EVENT,
                f"event {event_id!r} has invalid private extended properties",
            )
        private_properties = dict(private)

    recurring_event_id = raw.get("recurringEventId")
    if recurring_event_id is not None and not isinstance(recurring_event_id, str):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} has an invalid recurring event id",
        )

    start = _resource_time(raw.get("start"), "start")
    if start.error is not None:
        return Result.fail(start.error.code, start.error.message)
    end = _resource_time(raw.get("end"), "end")
    if end.error is not None:
        return Result.fail(end.error.code, end.error.message)
    if start.value is None or end.value is None:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"event {event_id!r} is missing its start or end time",
        )
    start_time, start_timezone = start.value
    end_time, end_timezone = end.value

    try:
        return Result.ok(
            Event(
                id=event_id,
                calendar_id=calendar_id,
                recurring_event_id=recurring_event_id,
                summary=summary,
                description=description,
                start=start_time,
                end=end_time,
                start_timezone=start_timezone,
                end_timezone=end_timezone,
                recurrence=recurrence,
                extended_properties=private_properties,
            )
        )
    except ValueError as exc:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar returned an invalid event {event_id!r}: {exc}",
        )


def _resource_time(
    raw: object,
    field: str,
) -> Result[tuple[datetime, str]]:
    """Extract a timed value and its IANA zone from ``start`` or ``end``."""
    if not isinstance(raw, dict):
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar event is missing a valid {field}",
        )
    date_time = raw.get("dateTime")
    if not isinstance(date_time, str) or not date_time.strip():
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar event is missing a timed {field}",
        )

    text = date_time.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    try:
        parsed = datetime.fromisoformat(text)
    except ValueError:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar event has an invalid {field} time",
        )
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        return Result.fail(
            ErrorCode.INVALID_EVENT,
            f"Google Calendar event has a naive {field} time",
        )

    timezone = raw.get("timeZone")
    if isinstance(timezone, str) and timezone.strip():
        return Result.ok((parsed, timezone.strip()))

    zone_key = getattr(parsed.tzinfo, "key", None)
    if isinstance(zone_key, str) and zone_key:
        return Result.ok((parsed, zone_key))

    # Google allows single events to carry only an offset in ``dateTime``.  A
    # zero offset is unambiguously UTC; any other offset has no IANA name here.
    if parsed.utcoffset() == timedelta(0):
        return Result.ok((parsed, "UTC"))
    return Result.fail(
        ErrorCode.INVALID_EVENT,
        f"Google Calendar event has a non-UTC offset but no IANA zone for {field}",
    )


def _items_from_response(
    raw: object,
    *,
    description: str = "event",
) -> Result[list[object]]:
    """Return the ``items`` list from a Google list response."""
    message = f"Google Calendar returned an invalid {description} list"
    if not isinstance(raw, dict):
        return Result.fail(ErrorCode.INVALID_EVENT, message)
    items = raw.get("items", [])
    if not isinstance(items, list):
        return Result.fail(ErrorCode.INVALID_EVENT, message)
    return Result.ok(items)


def _readable_calendar_id(item: object) -> str | None:
    """Return a usable calendar id, or ``None`` when the entry is skipped."""
    if not isinstance(item, dict):
        return None
    if item.get("deleted") is True:
        return None
    if item.get("selected") is False:
        return None
    if item.get("accessRole") not in _READABLE_ACCESS_ROLES:
        return None
    calendar_id = item.get("id")
    if not isinstance(calendar_id, str) or not calendar_id.strip():
        return None
    return calendar_id


def _next_page_token(raw: object) -> str | None:
    """Return a non-blank pagination token, if the response has one."""
    if not isinstance(raw, dict):
        return None
    token = raw.get("nextPageToken")
    if isinstance(token, str) and token.strip():
        return token
    return None


def _is_all_day_resource(raw: object) -> bool:
    """Whether a resource uses ``date`` instead of ``dateTime``."""
    if not isinstance(raw, dict):
        return False
    for field in ("start", "end"):
        value = raw.get(field)
        if (
            isinstance(value, dict)
            and "date" in value
            and "dateTime" not in value
        ):
            return True
    return False


def _error_from_exception(exc: BaseException) -> Error:
    """Map an ``HttpError`` or OAuth/network failure onto a stable error code."""
    if isinstance(exc, RefreshError):
        return Error(
            ErrorCode.AUTH_ERROR,
            f"Google Calendar authentication failed: {exc}",
        )
    if isinstance(exc, HttpError):
        status = _http_status(exc)
        return Error(_code_for_status(status), _http_error_message(status, exc))
    return Error(
        ErrorCode.UPSTREAM_ERROR,
        f"Google Calendar request failed: {exc}",
    )


def _http_status(error: HttpError) -> int | None:
    """Read the HTTP status from an ``HttpError`` defensively."""
    status = getattr(error, "status_code", None)
    if isinstance(status, int):
        return status
    response = getattr(error, "resp", None)
    status = getattr(response, "status", None)
    return status if isinstance(status, int) else None


def _code_for_status(status: int | None) -> ErrorCode:
    """Classify an HTTP status as a permanent or retryable provider error."""
    match status:
        case 400:
            return ErrorCode.INVALID_ARGUMENT
        case 401:
            return ErrorCode.AUTH_ERROR
        case 404 | 410:
            return ErrorCode.NOT_FOUND
        case 409:
            return ErrorCode.ALREADY_EXISTS
        case _:
            # 403, 429, 5xx, and unknown statuses are transient from the
            # caller's point of view; retrying is safe because creates use a
            # client id.  403 reason parsing is not implemented.
            return ErrorCode.UPSTREAM_ERROR


def _http_error_message(status: int | None, error: HttpError) -> str:
    """Format a Google HTTP error without assuming its payload shape."""
    reason = str(error)
    if status is None:
        return f"Google Calendar request failed: {reason}"
    return f"Google Calendar request failed with HTTP {status}: {reason}"
